# WampDeck setup - validates components, creates folders and writes all configs.
#
#   powershell -ExecutionPolicy Bypass -File .\scripts\setup.ps1
#   powershell -ExecutionPolicy Bypass -File .\scripts\setup.ps1 -Ssl -Hosts
#
# Components are bundled in .\bin - nothing is downloaded.

param(
    [switch]$Ssl,
    [switch]$Hosts
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot '..\lib\bootstrap.ps1')

Write-Host ''
Write-Host '  WampDeck setup' -ForegroundColor Cyan
Write-Host "  folder: $Root" -ForegroundColor DarkGray
Write-Host ''

# ---------------------------------------------------------------- components
$required = @(
    @{ Name = 'PHP 8.3';  Path = (Join-Path $PhpRoot '8.3.30\php-cgi.exe') },
    @{ Name = 'PHP 8.2';  Path = (Join-Path $PhpRoot '8.2.12\php-cgi.exe') },
    @{ Name = 'MySQL';    Path = $Mysqld },
    @{ Name = 'nginx';    Path = $NginxExe },
    @{ Name = 'Apache';  Path = $ApacheExe },
    @{ Name = 'HeidiSQL'; Path = $HeidiExe },
    @{ Name = 'Node';     Path = $NodeExe },
    @{ Name = 'Python';   Path = $PythonExe },
    @{ Name = 'Git';      Path = $GitExe },
    @{ Name = 'Composer'; Path = $ComposerBat },
    @{ Name = 'Mailpit';  Path = $MailpitExe },
    @{ Name = 'Redis';    Path = $RedisExe },
    @{ Name = 'Memcached'; Path = $MemcachedExe },
    @{ Name = 'ngrok';    Path = $NgrokExe },
    @{ Name = 'Cmder';    Path = $CmderExe },
    @{ Name = 'Notepad++'; Path = $NotepadExe },
    @{ Name = 'Cronical'; Path = $CronicalExe }
)

$missing = @()
foreach ($item in $required) {
    if (Test-Path $item.Path) {
        Write-Ok $item.Name
    } else {
        Write-Warn "$($item.Name) missing: $($item.Path)"
        $missing += $item.Name
    }
}

# ---------------------------------------------------------------- folders
foreach ($dir in @(
        $BinDir, $EtcDir, $LogDir, $TmpDir, $DownloadDir, $DataDir, $WwwDir,
        $PidDir, $SessionDir, $SslDir,
        (Join-Path $TmpDir 'nginx'), (Join-Path $TmpDir 'nginx\client_body'),
        (Join-Path $TmpDir 'nginx\proxy'), (Join-Path $TmpDir 'nginx\fastcgi'),
        (Join-Path $TmpDir 'nginx\uwsgi'), (Join-Path $TmpDir 'nginx\scgi'),
        (Join-Path $DataDir 'redis'), (Join-Path $DataDir 'mailpit')
    )) {
    Ensure-Dir $dir
}

# nginx opens its default log before reading the config.
foreach ($logFile in @('error.log', 'nginx-error.log', 'nginx-access.log', 'apache-error.log', 'apache-access.log')) {
    $path = Join-Path $LogDir $logFile
    if (-not (Test-Path $path)) { New-Item -ItemType File -Path $path | Out-Null }
}

# ---------------------------------------------------------------- composer shim
# The stock composer.bat calls "php" from PATH, which fails when Composer is
# invoked by the panel/CLI outside the bundled terminal. Regenerate a shim that
# uses the PHP shipped with this install (newest installed version wins).
$composerBat = Join-Path $BinDir 'composer\composer.bat'
$composerDir = Split-Path -Parent $composerBat
if (Test-Path $composerDir) {
    $shim = @"
@ECHO OFF
REM Generated by setup.ps1 - run Composer with WampDeck's own PHP.
set "WD_ROOT=%~dp0..\"
set "PHP_EXE="
for /d %%D in ("%WD_ROOT%php\*") do (
    if exist "%%D\php.exe" set "PHP_EXE=%%D\php.exe"
)
if not defined PHP_EXE (
    echo Composer: no PHP found in %WD_ROOT%php 1>&2
    exit /b 1
)
"%PHP_EXE%" "%~dp0composer.phar" %*
"@
    Set-Content -Path $composerBat -Value $shim -Encoding ASCII
    Write-Ok 'composer.bat shim written'
}

# ---------------------------------------------------------------- cacert
$caFile = Join-Path $EtcDir 'cacert.pem'
if (-not (Test-Path $caFile)) {
    foreach ($source in @('C:\laragon\etc\ssl\cacert.pem', 'C:\xampp\apache\bin\curl-ca-bundle.crt')) {
        if (Test-Path $source) {
            Copy-Item $source $caFile -Force
            Write-Ok 'cacert.pem copied'
            break
        }
    }
    if (-not (Test-Path $caFile)) { Write-Warn 'cacert.pem not found (PHP curl HTTPS may need it)' }
}

# ---------------------------------------------------------------- configs
Write-Step 'writing configuration files'
Write-AllConfigs
Write-Ok "php.ini for $($PhpVersions -join ', ')"
Write-Ok 'my.ini, redis.conf, nginx.conf'
Write-Ok 'Apache httpd.conf + vhosts'

# ---------------------------------------------------------------- database
if (-not (Test-Path (Join-Path $MysqlData 'mysql'))) {
    Write-Step 'initializing MySQL data directory (root, empty password)'
    Ensure-Dir $MysqlData
    $outLog = Join-Path $LogDir 'mysql-init.out.log'
    $errLog = Join-Path $LogDir 'mysql-init.err.log'
    $process = Start-Process -FilePath $Mysqld `
        -ArgumentList @("--defaults-file=`"$MyIni`"", '--initialize-insecure') `
        -Wait -PassThru -NoNewWindow `
        -RedirectStandardOutput $outLog -RedirectStandardError $errLog
    if ($process.ExitCode -ne 0 -or -not (Test-Path (Join-Path $MysqlData 'mysql'))) {
        Write-Err "MySQL initialization failed (exit $($process.ExitCode)). See logs\mysql-error.log"
    } else {
        Write-Ok 'MySQL initialized (user: root, password: empty)'
    }
} else {
    Write-Ok 'MySQL data directory already initialized'
}

# ---------------------------------------------------------------- ssl
if ($Ssl) {
    Write-Step 'creating local CA and wildcard certificate'
    $ssl = Initialize-Ssl
    if ($ssl.Trusted) {
        Write-Ok 'SSL certificate created and CA trusted (CurrentUser Root)'
    } else {
        Write-Warn 'SSL certificate created, but the CA could not be trusted automatically'
    }
    $State.ssl = $true
    Save-StackState
    Write-AllConfigs
}

# ---------------------------------------------------------------- hosts
if ($Hosts) {
    Write-Step 'syncing hosts file'
    if (Invoke-HostsSyncElevated) {
        Write-Ok 'hosts file updated'
    } else {
        Write-Warn 'hosts file not updated (UAC cancelled). Run .\hosts.cmd -Sync later.'
    }
}

# ---------------------------------------------------------------- test configs
if (Test-Path $NginxExe) {
    $previous = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    $nginxTest = & $NginxExe -p $Prefix -c 'etc/nginx.conf' -t 2>&1
    $nginxCode = $LASTEXITCODE
    $ErrorActionPreference = $previous
    if ($nginxCode -eq 0) {
        Write-Ok 'nginx config test passed'
    } else {
        Write-Err 'nginx config test failed'
        $nginxTest | ForEach-Object { Write-Host "    $_" -ForegroundColor DarkGray }
    }
}

if (Test-Path $ApacheExe) {
    $previous = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    $apacheTest = & $ApacheExe -t -f $ApacheMainConf 2>&1
    $apacheCode = $LASTEXITCODE
    $ErrorActionPreference = $previous
    if ($apacheCode -eq 0) {
        Write-Ok 'Apache config test passed'
    } else {
        Write-Err 'Apache config test failed'
        $apacheTest | ForEach-Object { Write-Host "    $_" -ForegroundColor DarkGray }
    }
}

# ---------------------------------------------------------------- summary
Write-Host ''
if ($missing.Count -gt 0) {
    Write-Warn "Missing components: $($missing -join ', ')"
}
Write-Host '  Setup complete.' -ForegroundColor Green
Write-Host ''
Write-Host '  Start:   .\start.cmd        (add -Open to launch the panel)' -ForegroundColor White
Write-Host '  GUI:     .\panel.cmd' -ForegroundColor White
Write-Host '  Panel:   http://localhost' -ForegroundColor White
Write-Host '  SSL:     .\ssl.cmd -Enable  (trusted https://name.test)' -ForegroundColor White
Write-Host '  Hosts:   .\hosts.cmd -Sync  (one UAC prompt)' -ForegroundColor White
Write-Host ''
